-- A booking groups the seats of one order. It holds them for 5 minutes as RESERVED; unpaid by
-- expires_at, its seats count as free again. Times are local cinema time, like schedules.

create table bookings (
    booking_id  integer generated by default as identity primary key,
    user_id     integer     not null references users (user_id),
    schedule_id integer     not null references schedules (schedule_id),
    status      varchar(10) not null, -- RESERVED or PAID
    created_at  timestamp   not null,
    expires_at  timestamp   not null,
    paid_at     timestamp
);

-- deleting a booking (cancelled or expired) frees its seats
alter table tickets add column booking_id integer;
alter table tickets add constraint fk_tickets_booking
    foreign key (booking_id) references bookings (booking_id) on delete cascade;

-- tickets booked before bookings existed: one paid booking per user and show
insert into bookings (user_id, schedule_id, status, created_at, expires_at, paid_at)
select user_id, schedule_id, 'PAID', localtimestamp, localtimestamp, localtimestamp
from tickets
group by user_id, schedule_id;

update tickets
set booking_id = (select b.booking_id from bookings b
                  where b.user_id = tickets.user_id and b.schedule_id = tickets.schedule_id);

alter table tickets alter column booking_id set not null;
